package org.bibleplugin.source.catalog;

import com.google.gson.Gson;
import com.google.gson.JsonParseException;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import org.bibleplugin.core.exception.BibleException;
import org.bibleplugin.core.exception.BibleException.Problem;
import org.bibleplugin.core.model.BibleInfo;
import org.bibleplugin.core.readability.Difficulty;
import org.bibleplugin.core.readability.Readability;

/**
 * The list of Bible editions the plugin can download. Backed by the {@code catalog.json} resource
 * generated by {@code tools/generate-catalog.py}; immutable after loading.
 */
public final class BibleCatalogue {

    /** Bundled resource path, relative to this class. */
    public static final String RESOURCE = "/catalog.json";

    private static final Gson GSON = new Gson();

    private final Map<String, CatalogueEntry> entries;

    private BibleCatalogue(Map<String, CatalogueEntry> entries) {
        this.entries = Collections.unmodifiableMap(entries);
    }

    /** Loads the catalogue that ships inside the jar. */
    public static BibleCatalogue bundled() {
        try (InputStream stream = BibleCatalogue.class.getResourceAsStream(RESOURCE)) {
            if (stream == null) {
                throw new BibleException(Problem.STORAGE_ERROR, "The bundled catalogue " + RESOURCE + " is missing.");
            }
            return read(stream);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Reads a catalogue in the {@code catalog.json} schema. */
    public static BibleCatalogue read(InputStream stream) {
        try (Reader reader = new InputStreamReader(stream, StandardCharsets.UTF_8)) {
            CatalogueFile file = GSON.fromJson(reader, CatalogueFile.class);
            if (file == null || file.entries == null) {
                throw new BibleException(Problem.FORMAT_ERROR, "The catalogue has no entries.");
            }
            Map<String, CatalogueEntry> map = new LinkedHashMap<>();
            for (EntryDto dto : file.entries) {
                CatalogueEntry entry = dto.toEntry();
                map.put(entry.id(), entry);
            }
            return new BibleCatalogue(map);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        } catch (JsonParseException e) {
            throw new BibleException(Problem.FORMAT_ERROR, "The catalogue is not valid JSON: " + e.getMessage(), e);
        }
    }

    public Optional<CatalogueEntry> find(String id) {
        return Optional.ofNullable(entries.get(id.toLowerCase(Locale.ROOT)));
    }

    /** @return every edition, sorted by language then name. */
    public List<CatalogueEntry> all() {
        return entries.values().stream()
                .sorted(Comparator.comparing(CatalogueEntry::language).thenComparing(CatalogueEntry::name))
                .toList();
    }

    public List<CatalogueEntry> byLanguage(String languageCode) {
        return all().stream().filter(e -> e.languageCode().equalsIgnoreCase(languageCode)).toList();
    }

    /** @return the distinct language codes, in alphabetical order of their language names. */
    public List<String> languageCodes() {
        return all().stream().map(CatalogueEntry::languageCode).distinct().toList();
    }

    public int size() {
        return entries.size();
    }

    /** Editions that have a measured reading difficulty, easiest first. */
    public List<CatalogueEntry> rated() {
        return all().stream()
                .filter(e -> e.readability().isPresent())
                .sorted(Comparator.comparingDouble(e -> e.readability().get().gradeLevel()))
                .toList();
    }

    private static final class CatalogueFile {
        List<EntryDto> entries;
    }

    private static final class EntryDto {
        String id;
        String name;
        String languageCode;
        String language;
        String license;
        String year;
        String url;
        ReadabilityDto readability;

        CatalogueEntry toEntry() {
            BibleInfo info = new BibleInfo(id, name, languageCode, language, license);
            Optional<Readability> measured = readability == null ? Optional.empty()
                    : Optional.of(new Readability(readability.readingEase, readability.gradeLevel,
                            Difficulty.valueOf(readability.difficulty)));
            try {
                return new CatalogueEntry(info, year, URI.create(url), measured);
            } catch (IllegalArgumentException invalid) {
                throw new BibleException(Problem.FORMAT_ERROR, "Bad catalogue entry " + id + ": " + invalid.getMessage(), invalid);
            }
        }
    }

    private static final class ReadabilityDto {
        double readingEase;
        double gradeLevel;
        String difficulty;
    }
}
